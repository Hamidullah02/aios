// bootstrapEligible reports whether a command should get the
// first-run workspace.
//
// The commands that do work get it: web, fix, run, resume. They
// are the ones an operator reaches for, and each of them failed
// on a workspace that had never been set up -- `aios web` served
// a UI with a dead submit button, and `aios fix` could not open
// its audit database because the var/ directory did not exist.
//
// The commands that do not get it:
//
//   - init is the bootstrap itself;
//   - daemon manages the approval daemon;
//   - report and audit read a run that already happened, so a
//     missing workspace is a real answer, not something to
//     paper over with an empty one;
//   - tools and approve/deny do not touch the workspace.
func bootstrapEligible(command string) bool {
	switch command {
	case CmdWeb, CmdFix, CmdRun, CmdResume:
		return true
	default:
		return false
	}
}

// bootstrapWorkspace creates the workspace a run needs, if it is
// not there yet.
//
// This is what makes `aios web` work in a directory the operator
// has never used before. The install script's last instruction
// is "put your key in a .env file, then run aios web", and
// nothing in that sentence creates a workspace -- so before this
// function existed, `aios web` in a fresh directory served a UI
// whose submit button was dead, with a 503 saying "this server
// cannot start tasks". The operator had to guess that they were
// supposed to run `aios init` first.
//
// The rule this function applies is simple: the workspace is the
// directory the operator is standing in.
//
// It is NOT the directory the config file lives in. That was the
// old default, and it means the agent's world is the same folder
// as the tool's own config -- so "write a file called notes.txt"
// produces var/notes.txt, a file the operator has to go looking
// for. An operator standing in their project directory expects
// the file to land next to them.
//
// The tool's own state (audit log, policy, prices) still goes in
// the var/ subdirectory, because that is where `aios init`
// scaffolds it and where operators expect to find it.
//
// The function returns the workspace root and the directory the
// tool's state lives in.
func bootstrapWorkspace(operatorDir string) (workspace string, stateDir string, err error) {
	if operatorDir == "" {
		operatorDir = "."
	}
	abs, err := filepath.Abs(operatorDir)
	if err != nil {
		return "", "", err
	}
	stateDir = filepath.Join(abs, "var")
	if mkErr := os.MkdirAll(stateDir, 0o755); mkErr != nil {
		return "", "", mkErr
	}
	return abs, stateDir, nil
}

// firstRunPolicyYAML is the policy used when the operator has not
// written one.
//
// Read-only tools are allowed, file-editing tools are allowed,
// and everything that runs a subprocess is gated behind an
// approval. That is the right default for a tool that can run
// commands: the commands are the dangerous part, and the
// operator still gets to say no to each one.
//
// It is not the `aios init` default, which allows only the
// read-only tools. That default is right for a tool an expert
// configures before handing to a colleague, and wrong for the
// first run of a tool whose whole job is to do what the
// operator asked: the operator said "write the word hello into a
// file called hi.txt" and got a run that failed with "write
// denied by policy: no rule matched; default deny".
//
// The tool list is NOT written out by hand here -- it is
// generated by firstRunPolicyYAMLFor from the registered tool
// set and the tools' own risk tiers. A hand-written list drifts:
// the one in this file named "apply_patch", which is not a
// registered tool, and missed nine that are, so the agent
// could not read a notebook, run the tests, or commit a change
// on a workspace that had never been configured. Deriving it
// removes the class of bug rather than the instance.
//
// This constant is the fallback for the case where the tool set
// cannot be built. It is intentionally a subset -- the safe
// tools -- so a workspace that somehow gets this instead of the
// generated policy still works for the common case.
const firstRunPolicyYAML = `# aios first-run policy.
#
# This file was created for you on first run, so that the tool
# can do what you asked. It allows the read, search, and
# file-editing tools. Anything that runs a subprocess is gated
# behind an approval: you will be asked before it happens.
#
# Edit this file to change what the agent is allowed to do.
# Rules are matched in order; the first match wins, and the
# default is deny.
default: deny
rules:
  - id: allow-read
    match:
      tool: read_file
    action: allow
  - id: allow-search
    match:
      tool: search_files
    action: allow
  - id: allow-glob
    match:
      tool: glob
    action: allow
  - id: allow-grep
    match:
      tool: grep
    action: allow
  - id: allow-code-search
    match:
      tool: code_search
    action: allow
  - id: allow-write
    match:
      tool: write_file
    action: allow
  - id: allow-write-alias
    match:
      tool: write
    action: allow
  - id: allow-edit
    match:
      tool: edit
    action: allow
  - id: allow-multi-edit
    match:
      tool: multi_edit
    action: allow
  - id: allow-apply-patch
    match:
      tool: apply_patch
    action: allow
  - id: allow-git-status
    match:
      tool: git_status
    action: allow
  - id: allow-git-diff
    match:
      tool: git_diff
    action: allow
  - id: allow-git-log
    match:
      tool: git_log
    action: allow
  - id: allow-ask-user
    match:
      tool: ask_user
    action: allow
  - id: ask-shell
    match:
      tool: run_shell
    action: ask
    reason: shell access is gated by the approval daemon
    approval:
      action: shell
      resource: "{arg.command}"
      reason: "run a shell command"
`

// firstRunPolicyYAMLFor generates the first-run policy from the
// tools that are actually registered.
//
// The rule for each tool comes from its own risk tier, which the
// tool declares:
//
//   - tier 0 -- read-only. Allowed.
//   - tier 1 -- changes files inside the workspace, and nothing
//     else. Allowed. These tools cannot run a command, reach the
//     network, or touch anything outside the workspace root.
//   - tier 2 -- runs a subprocess. Gated behind an approval, so
//     the operator sees the command before it runs.
//
// Deriving the list means a tool added to the bus is allowed (or
// gated) by the first run automatically, and a tool removed from
// the bus leaves no rule behind. There is no second list to
// keep in step.
//
// The tools that need an approval get one rule each. The
// approval's resource is the tool's own argument, so the
// operator's browser shows the command that is about to run
// rather than a generic label.
//
// If the tool set cannot be built, the caller gets the
// hand-written fallback, which is a safe subset.
func firstRunPolicyYAMLFor(toolSet map[string]tools.Tool) string {
	if len(toolSet) == 0 {
		return firstRunPolicyYAML
	}
	names := make([]string, 0, len(toolSet))
	for name := range toolSet {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString(`# aios first-run policy.
#
# This file was created for you on first run, so that the tool
# can do what you asked. It allows the read, search, and
# file-editing tools. Anything that runs a subprocess is gated
# behind an approval: you will be asked before it happens.
#
# Edit this file to change what the agent is allowed to do.
# Rules are matched in order; the first match wins, and the
# default is deny.
default: deny
rules:
`)
	for _, name := range names {
		tier := tools.Tier(toolSet[name])
		switch {
		case tier <= 1:
			fmt.Fprintf(&buf, "  - id: allow-%s\n    match:\n      tool: %s\n    action: allow\n", name, name)
		default:
			// A subprocess tool. It is gated, and the
			// operator is shown what is about to run.
			//
			// The resource template names the tool's OWN
			// argument, not a fixed "command". A fixed name
			// breaks for every tool that spells it
			// differently: git_commit takes "message",
			// diagnostics takes "checker", and a template
			// naming an argument the call does not carry is
			// a hard error. The rule then fails with
			// "approval.resource: template: arg.command: not
			// in args" -- the operator's approval is dead
			// and the tool can never run.
			resource, reason := approvalResourceFor(toolSet[name])
			fmt.Fprintf(&buf,
				"  - id: ask-%s\n    match:\n      tool: %s\n    action: ask\n    reason: %s runs a subprocess, so it is gated behind an approval\n    approval:\n      action: %s\n      resource: \"%s\"\n      reason: \"%s\"\n",
				name, name, name, name, resource, reason)
		}
	}
	return buf.String()
}

// approvalResourceFor picks the approval template for a tool.
//
// The resource is what the operator's browser shows next to the
// Allow button, so it has to name the thing the tool is about to
// do: the command for run_shell, the commit message for
// git_commit, the checker for diagnostics.
//
// The template names an argument the tool actually has. A
// template naming an argument the call does not carry is a hard
// error in the policy gateway, and the rule then fails with
// "template: arg.command: not in args" -- so a wrong name does
// not degrade, it breaks the tool completely.
//
// The argument is chosen from the tool's own JSON schema, with
// a preference order for the names that describe the action.
// When the schema names none of them, the template falls back
// to "{tool}", which always resolves.
func approvalResourceFor(tool tools.Tool) (resource string, reason string) {
	name := tool.Name()
	// The names that describe what the tool is about to do,
	// best first.
	preferred := []string{"command", "message", "checker", "path", "runner", "name"}
	have := schemaArgNames(tool)
	for _, p := range preferred {
		for _, h := range have {
			if h == p {
				return "{arg." + p + "}", "run " + name
			}
		}
	}
	if len(have) > 0 {
		// The schema names arguments, just not ones we
		// recognise. Use the first one: it is a real
		// argument, so the template resolves.
		return "{arg." + have[0] + "}", "run " + name
	}
	return "{tool}", "run " + name
}

// schemaArgNames returns the argument names a tool's input
// schema declares.
//
// The schema is the raw JSON Schema the planner hands the
// model. Its "properties" object maps an argument name to its
// type, and the keys are the argument names.
func schemaArgNames(tool tools.Tool) []string {
	_, schema := tools.Describe(tool)
	if schema == "" {
		return nil
	}
	var parsed struct {
		Properties map[string]json.RawMessage `json:"properties"`
	}
	if err := json.Unmarshal([]byte(schema), &parsed); err != nil {
		return nil
	}
	names := make([]string, 0, len(parsed.Properties))
	for n := range parsed.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

// firstRunEgressYAML is the egress policy used when the operator
// has not written one.
//
// It allows the model provider, because without it the tool
// cannot call the model at all -- which is the same as not
// working. The subprocess guard uses this list to decide what a
// tool's child processes may reach.
const firstRunEgressYAML = `# aios first-run egress policy.
#
# The hosts a tool's subprocesses may reach. The model provider
# has to be here, or the agent cannot call the model.
allow:
  - openrouter.ai
  - api.openai.com
  - api.anthropic.com
deny: []
headers:
  remove: []
  add: {}
`

// ensureWorkspaceReady makes the workspace usable and returns the
// paths the caller needs.
//
// It does three things, in order:
//
//  1. Creates var/ if it is not there.
//  2. Writes the policy, egress, prices, and config files if
//     they are not there. Existing files are left alone, so an
//     operator who has already tuned their policy keeps it.
//  3. Returns the operator's directory as the workspace root,
//     and the var/ directory as the tool's state directory.
//
// The policy and egress that get written are the first-run ones,
// not the `aios init` defaults. The difference matters: the
// `aios init` default allows only read-only tools, so an
// operator who said "write the word hello into a file called
// hi.txt" got a run that failed with "write denied by policy: no
// rule matched; default deny". The tool refusing the exact
// thing it was asked to do, on a fresh workspace, with nothing
// in the message about how to fix it.
//
// The first-run policy allows the read, search, and file-editing
// tools. Those tools change files inside the workspace and
// nothing else: they cannot run a command, reach the network, or
// touch anything outside the workspace root. Shell access stays
// gated behind an approval, so a careful operator still gets to
// say no to a command.
func ensureWorkspaceReady(operatorDir string) (workspace string, stateDir string, created []string, err error) {
	workspace, stateDir, err = bootstrapWorkspace(operatorDir)
	if err != nil {
		return "", "", nil, err
	}
	// The files the first run needs, in the order they are
	// written. The policy comes first because it is the one
	// that decides whether the tool can do what was asked.
	//
	// The policy is generated from the registered tool set, so
	// it names every tool that can actually be dispatched and
	// nothing that cannot.
	files := []struct {
		name string
		body string
	}{
		{"policy.yaml", firstRunPolicyYAMLFor(productionToolSet(nil, nil))},
		{"egress.yaml", firstRunEgressYAML},
		{"prices.yaml", defaultPricesYAML},
		{"config.yaml", defaultConfigYAML},
	}
	for _, f := range files {
		path := filepath.Join(stateDir, f.name)
		if _, statErr := os.Stat(path); statErr == nil {
			continue
		}
		if writeErr := os.WriteFile(path, []byte(f.body), 0o644); writeErr != nil {
			return "", "", created, writeErr
		}
		created = append(created, path)
	}
	return workspace, stateDir, created, nil
}
